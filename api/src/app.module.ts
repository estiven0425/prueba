import { Module } from '@nestjs/common';
import { SequelizeModule } from '@nestjs/sequelize';
import { CuentasModule } from './cuentas/cuentas.module.js';

@Module({
  imports: [
    SequelizeModule.forRoot({
      dialect: 'sqlite',
      storage: './database.sqlite',
      autoLoadModels: true,
      synchronize: true,
    }),
    CuentasModule,
  ],
})
export class AppModule {}